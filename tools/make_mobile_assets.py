#!/usr/bin/env python3
"""v2.2 mobile assets: 256px jelly sprites + 256px octopus B material (inlined data URIs), UI icons downscaled to
192px max side (≈3x their largest on-screen size), every runtime PNG re-encoded losslessly (zlib 9 + optimize).
Source of truth = the v2.1 build (../game_v2.1). Nine-slice components keep their pixel size (SLICE margins are in source px).
usage: python3 tools/make_mobile_assets.py <v2.1 dir> <v2.2 dir>"""
import base64, io, json, os, re, sys
from PIL import Image

src, dst = sys.argv[1], sys.argv[2]
SPR = 256; ICON_MAX = 192

def png_bytes(im):
    b = io.BytesIO(); im.save(b, 'PNG', optimize=True, compress_level=9); return b.getvalue()

def resize_rgba(im, w, h):  # premultiplied resample (no dark/bright fringes at alpha edges)
    return im.convert('RGBa').resize((w, h), Image.LANCZOS).convert('RGBA')

def data_uri(b): return 'data:image/png;base64,' + base64.b64encode(b).decode()
def decode_uri(u): return Image.open(io.BytesIO(base64.b64decode(u.split(',', 1)[1])))

report = {}
# 1) jelly sprites
s = open(os.path.join(src, 'js/sprites.js')).read()
m = re.search(r'window\.JELLY_SPRITES = (\{.*\});', s, re.S)
spr = json.loads(m.group(1)); out = {}
for k, u in spr.items():
    im = decode_uri(u).convert('RGBA'); b = png_bytes(resize_rgba(im, SPR, SPR)); out[k] = data_uri(b)
    report[k] = [len(base64.b64decode(u.split(',', 1)[1])), len(b)]
hdr = s[:s.index('window.JELLY_SPRITES')]
hdr = hdr.replace('asset pack 512px PNGs', 'asset pack PNGs, v2.2 mobile: Lanczos-downscaled to 256px by tools/make_mobile_assets.py')
open(os.path.join(dst, 'js/sprites.js'), 'w').write(hdr + 'window.JELLY_SPRITES = ' + json.dumps(out) + ';\n')

# 2) octopus B material (base = premultiplied colour, mat = data channels → plain resample)
s = open(os.path.join(src, 'js/material_octopus.js')).read()
def sub(name, premul):
    global s
    mm = re.search(r"JM\.MAT\.jelly_octopus\.%s = '([^']+)'" % name, s)
    im = decode_uri(mm.group(1))
    if premul: im2 = resize_rgba(im.convert('RGBA'), SPR, SPR)
    else: im2 = im.resize((SPR, SPR), Image.LANCZOS)
    b = png_bytes(im2); report['octo_' + name] = [len(base64.b64decode(mm.group(1).split(',', 1)[1])), len(b)]
    s = s.replace(mm.group(1), data_uri(b))
sub('base', True); sub('mat', False)
s = s.replace('/* generated by tools/make_octopus_material.py', '/* generated by tools/make_octopus_material.py (v2.2: textures downscaled to 256px by tools/make_mobile_assets.py)')
open(os.path.join(dst, 'js/material_octopus.js'), 'w').write(s)

# 3) UI icons (drawn via drawImg only) → 192 max side; components / board / bg: lossless re-encode only
for d in ['assets/ui/icons', 'assets/ui/components', 'assets/board']:
    for f in sorted(os.listdir(os.path.join(src, d))):
        if not f.endswith('.png'): continue
        im = Image.open(os.path.join(src, d, f)).convert('RGBA'); w, h = im.size
        if d.endswith('icons') and max(w, h) > ICON_MAX:
            k = ICON_MAX / max(w, h); im = resize_rgba(im, max(1, round(w * k)), max(1, round(h * k)))
        b = png_bytes(im); o = os.path.getsize(os.path.join(src, d, f))
        if len(b) >= o and im.size == (w, h): b = open(os.path.join(src, d, f), 'rb').read()   # keep the smaller file
        open(os.path.join(dst, d, f), 'wb').write(b); report[d + '/' + f] = [o, len(b)]
json.dump(report, open(os.path.join(dst, 'tools/mobile_assets_report.json'), 'w'), indent=1)
t0 = sum(v[0] for v in report.values()); t1 = sum(v[1] for v in report.values())
print('assets (decoded bytes) %.0f KB -> %.0f KB' % (t0 / 1024, t1 / 1024))
